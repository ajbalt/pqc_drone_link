#!/usr/bin/env python3
"""Turn the raw benchmark, loss-run and capture files into the data files of Progress Report 2.

Usage: python3 -I docs/report/prepare_data2.py RESULTS_DIR CAPTURE_DIR OUT_DIR [BUILD_DIR]

Reads from RESULTS_DIR:
  t10_handshake_loopback_*.ok.csv     with matching *.server_A.csv and *.server_B.csv
                                      (only runs that HAVE server files are used)
  t08_loss_loopback_*.runs.csv        the newest one
and from CAPTURE_DIR the files written by scripts/capture_demo.sh. It writes into OUT_DIR:
  numbers2.tex          LaTeX macros the report text uses, so no number is ever typed by hand
  box_server_cpu_ms.tex, box_client_cpu_ms2.tex   generated \\addplot lines for box plots
  loss_table.tex        the rows of the T08 table
  loss_drain.csv        median drain time per loss level for the plot
  wire_table.tex        the rows of the on-the-wire table

Nothing here estimates or edits a measurement: every figure comes from the raw files, and the
script can be rerun by anyone. It refuses rows from a Debug build. Standard library only.
Existing output files are overwritten because they are derived data, not results.
"""
import csv
import glob
import math
import os
import statistics
import subprocess
import sys


def pct(sorted_vals, p):
    """Nearest-rank percentile, p in (0, 100]."""
    return sorted_vals[math.ceil(p / 100 * len(sorted_vals)) - 1]


def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def tex(s):
    for a, b in (("\\", " "), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"),
                 ("$", r"\$"), ("{", r"\{"), ("}", r"\}"), ("~", " "), ("^", " ")):
        s = s.replace(a, b)
    return s


def kv_file(path):
    out = {}
    if os.path.exists(path):
        for line in open(path):
            if line.startswith("---"):
                break
            if "=" in line:
                k, v = line.rstrip("\n").split("=", 1)
                out.setdefault(k, v)
    return out


def box_lines(path, series):
    """series: [(position, config, sorted values)] -> a file of \\addplot lines."""
    lines = ["% Generated by prepare_data2.py. Do not edit."]
    for pos, cfg, v in series:
        st = [pct(v, 5), pct(v, 25), statistics.median(v), pct(v, 75), pct(v, 95)]
        lines.append(
            f"\\addplot+[boxplot prepared={{draw position={pos}, lower whisker={st[0]:.4f}, "
            f"lower quartile={st[1]:.4f}, median={st[2]:.4f}, upper quartile={st[3]:.4f}, "
            f"upper whisker={st[4]:.4f}}}, fill=color{cfg}!25, draw=color{cfg}!80!black] "
            f"coordinates {{}};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def t10(results, out, macros):
    runs = []
    for ok in sorted(glob.glob(os.path.join(results, "t10_handshake_loopback_*.ok.csv"))):
        base = ok[:-len(".ok.csv")]
        if os.path.exists(base + ".server_A.csv") and os.path.exists(base + ".server_B.csv"):
            runs.append(base)
    if not runs:
        raise SystemExit("no T10 run with server files in " + results)
    cli = {"A": [], "B": []}
    srv = {"A": [], "B": []}
    peak = {"A": 0, "B": 0}
    builds = set()
    for base in runs:
        rows = read(base + ".ok.csv")
        builds |= {r["build"] for r in rows}
        for cfg in ("A", "B"):
            mine = [r for r in rows if r["config"] == cfg]
            warm = sum(1 for r in mine if r["warmup"] == "1")
            cli[cfg] += [r for r in mine if r["warmup"] == "0"]
            srows = read(f"{base}.server_{cfg}.csv")
            peak[cfg] = max(peak[cfg], max(int(r["rss_peak_kb"]) for r in srows))
            good = [r for r in srows if r["ok"] == "1"]
            srv[cfg] += good[warm:]
    if builds != {"release"}:
        raise SystemExit(f"refusing: not all client rows are from a release build: {builds}")
    for cfg in ("A", "B"):
        if len(cli[cfg]) != len(srv[cfg]):
            raise SystemExit(f"client and server counts differ for {cfg}: "
                             f"{len(cli[cfg])} vs {len(srv[cfg])}")

    def col(rows, c, div=1.0):
        return sorted(float(r[c]) / div for r in rows)

    for cfg in ("A", "B"):
        macros[f"NHs{cfg}"] = str(len(cli[cfg]))
        for name, rows, c, div in (
                ("CliLat", cli[cfg], "latency_total_ns", 1e6),
                ("CliCpu", cli[cfg], "client_cpu_ns", 1e6),
                ("CliHeap", cli[cfg], "heap_delta_bytes", 1024.0),
                ("SrvCpu", srv[cfg], "server_cpu_ns", 1e6),
                ("SrvHeap", srv[cfg], "heap_delta_bytes", 1024.0)):
            v = col(rows, c, div)
            macros[f"{name}Med{cfg}"] = f"{statistics.median(v):.3f}" if div == 1e6 \
                else f"{statistics.median(v):.1f}"
            macros[f"{name}Pnf{cfg}"] = f"{pct(v, 95):.3f}" if div == 1e6 \
                else f"{pct(v, 95):.1f}"
        macros[f"SrvRx{cfg}"] = f"{statistics.median(col(srv[cfg], 'bytes_rx')):.0f}"
        macros[f"SrvTx{cfg}"] = f"{statistics.median(col(srv[cfg], 'bytes_tx')):.0f}"
        macros[f"CliTx{cfg}"] = f"{statistics.median(col(cli[cfg], 'bytes_tx')):.0f}"
        macros[f"CliRx{cfg}"] = f"{statistics.median(col(cli[cfg], 'bytes_rx')):.0f}"
        macros[f"SrvRss{cfg}"] = str(peak[cfg])
    # The two sides must have counted the same bytes (client tx = server rx and the reverse).
    same = all(c["bytes_tx"] == s["bytes_rx"] and c["bytes_rx"] == s["bytes_tx"]
               for cfg in ("A", "B") for c, s in zip(cli[cfg], srv[cfg]))
    macros["BytesAgree"] = "yes" if same else "NO"
    macros["SrvCpuRatio"] = f"{statistics.median(col(srv['B'], 'server_cpu_ns')) / statistics.median(col(srv['A'], 'server_cpu_ns')):.2f}"
    macros["CliCpuRatio"] = f"{statistics.median(col(cli['B'], 'client_cpu_ns')) / statistics.median(col(cli['A'], 'client_cpu_ns')):.2f}"
    macros["NTenSessions"] = str(len(runs))
    meta = kv_file(runs[0] + ".meta.txt")
    macros["TenDate"] = tex(meta.get("date_utc", "unknown")[:10])
    macros["TenCpu"] = tex(meta.get("cpu_model", "unknown"))
    box_lines(os.path.join(out, "box_server_cpu_ms.tex"),
              [(1, "A", col(srv["A"], "server_cpu_ns", 1e6)),
               (2, "B", col(srv["B"], "server_cpu_ns", 1e6))])
    box_lines(os.path.join(out, "box_client_cpu_ms2.tex"),
              [(1, "A", col(cli["A"], "client_cpu_ns", 1e6)),
               (2, "B", col(cli["B"], "client_cpu_ns", 1e6))])


def t08(results, out, macros):
    files = sorted(glob.glob(os.path.join(results, "t08_loss_loopback_*.runs.csv")))
    if not files:
        raise SystemExit("no T08 runs in " + results)
    rows = read(files[-1])
    meta = kv_file(files[-1].replace(".runs.csv", ".meta.txt"))
    groups = {}
    for r in rows:
        groups.setdefault((r["config"], r["loss_percent"]), []).append(r)

    def num(r, c):
        try:
            return float(r[c])
        except (KeyError, ValueError):
            return None

    def delivered(r):
        a, p, k, s = (num(r, c) for c in ("accepted", "pending", "acked", "stored"))
        return None not in (a, p, k, s) and p == 0 and k == a and s == a

    losses = sorted({int(r["loss_percent"]) for r in rows})
    table, drain = [], {}
    for (cfg, loss) in sorted(groups, key=lambda k: (int(k[1]), k[0])):
        rs = groups[(cfg, loss)]
        def med(c):
            v = sorted(x for x in (num(r, c) for r in rs) if x is not None and x >= 0)
            return statistics.median(v) if v else float("nan")
        dr = sorted(x for x in (num(r, "drain_ms") for r in rs) if x is not None and x >= 0)
        d_med = statistics.median(dr) if dr else float("nan")
        d_p95 = pct(dr, 95) if dr else float("nan")
        drain.setdefault(loss, {})[cfg] = d_med
        def thou(x):  # 5114 -> 5\,114 (a thin space), "-" for a missing value
            return "-" if x != x else f"{x:,.0f}".replace(",", "\\,")
        table.append(f"{cfg} & {loss}\\,\\% & {len(rs)} & {sum(delivered(r) for r in rs)} & "
                     f"{med('lost_links'):.0f} & {med('tcp_retrans_segs'):.0f} & "
                     f"{thou(d_med)} & {thou(d_p95)} & {med('duration_ms') / 1000:.1f}")
    with open(os.path.join(out, "loss_table.tex"), "w") as f:
        # Rows are separated by \\ but the last has none: the report adds it. A \\ at the very end
        # of an \input file confuses LaTeX's table lookahead ("Misplaced \noalign").
        f.write("% Generated by prepare_data2.py. Do not edit.\n" + " \\\\\n".join(table) + "\n")
    with open(os.path.join(out, "loss_drain.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["loss", "A", "B"])
        for loss in losses:
            w.writerow([loss, f"{drain[str(loss)].get('A', float('nan')):.1f}",
                        f"{drain[str(loss)].get('B', float('nan')):.1f}"])
    macros["EightRuns"] = str(len(rows))
    macros["EightPerCell"] = str(max(len(v) for v in groups.values()))
    macros["EightDelivered"] = str(sum(delivered(r) for r in rows))
    macros["EightRejected"] = str(int(sum(num(r, "rejected") or 0 for r in rows)))
    macros["EightRecords"] = tex(rows[0]["records"])
    macros["EightRate"] = tex(rows[0]["rate_hz"])
    macros["EightMtu"] = tex(rows[0]["netem"].split("mtu=")[-1])
    macros["EightDate"] = tex(meta.get("date_utc", "unknown")[:10])
    macros["EightMaxLoss"] = str(losses[-1])


def wire(capdir, out, macros):
    def fields(path, d):
        for line in open(path):
            if line.startswith(f"dir={d} "):
                return dict(p.split("=") for p in line.split()[1:])
        raise SystemExit(f"no {d} line in {path}")

    rows = []
    for name, label in (("A", "A"), ("B", "B")):
        c = fields(os.path.join(capdir, f"wire_{name}.front.txt"), "c2s")
        s = fields(os.path.join(capdir, f"wire_{name}.front.txt"), "s2c")
        rows.append(f"{label} & client $\\to$ server & {c['packets']} & {c['payload_bytes']} & "
                    f"{c['frame_bytes']}")
        rows.append(f" & server $\\to$ client & {s['packets']} & {s['payload_bytes']} & "
                    f"{s['frame_bytes']}")
        macros[f"Wire{name}Over"] = str(int(c["frame_bytes"]) + int(s["frame_bytes"])
                                        - int(c["payload_bytes"]) - int(s["payload_bytes"]))
        macros[f"Wire{name}Pkts"] = str(int(c["packets"]) + int(s["packets"]))
        macros[f"Wire{name}Retx"] = str(int(c["retransmissions"]) + int(s["retransmissions"]))
        # the proxy counted the same stream: the payload must agree
        proxy = open(os.path.join(capdir, f"wire_{name}.proxy.txt")).read().splitlines()
        pc = next(l for l in proxy if l.startswith("conn=1 dir=c2s"))
        ps = next(l for l in proxy if l.startswith("conn=1 dir=s2c"))
        pc = dict(p.split("=") for p in pc.split()[2:] if "=" in p)
        ps = dict(p.split("=") for p in ps.split()[2:] if "=" in p)
        macros[f"Wire{name}Agree"] = "yes" if (pc["bytes"] == c["payload_bytes"]
                                               and ps["bytes"] == s["payload_bytes"]) else "NO"
        macros[f"Wire{name}Groups"] = tex(pc["hello_groups"])
        macros[f"Wire{name}Suite"] = tex(pc["hello_ciphers"])
        macros[f"Wire{name}Chosen"] = tex(ps["server_keyshare"])
    with open(os.path.join(out, "wire_table.tex"), "w") as f:
        f.write("% Generated by prepare_data2.py. Do not edit.\n" + " \\\\\n".join(rows) + "\n")
    # the tampered run: what the proxy damaged, and what the client then did
    px = open(os.path.join(capdir, "wire_B_tamper.proxy.txt")).read()
    client = open(os.path.join(capdir, "wire_B_tamper.client.txt")).read()
    done = next(l for l in client.splitlines() if l.startswith("done "))
    kvs = dict(p.split("=") for p in done.split()[1:])
    macros["TamperLost"] = kvs["lost_links"]
    macros["TamperAcked"] = kvs["acked"]
    macros["TamperTampered"] = str(px.count("tampered=1"))
    server = open(os.path.join(capdir, "wire_B_tamper.server.txt")).read()
    macros["TamperServerErr"] = str(server.count("protocol_error=1"))
    macros["TamperDup"] = str(sum(int(l.split("duplicates=")[1].split()[0])
                                  for l in server.splitlines() if "conn_done" in l))


def main(results, capdir, out, build=None):
    os.makedirs(out, exist_ok=True)
    macros = {}
    t10(results, out, macros)
    t08(results, out, macros)
    wire(capdir, out, macros)
    if build:
        try:
            lines = subprocess.run(["ctest", "--test-dir", build, "-N"], capture_output=True,
                                   text=True, check=True).stdout.splitlines()
            total = next(l for l in lines if l.startswith("Total Tests:"))
            macros["NTests"] = total.split(":")[1].strip()
        except (OSError, subprocess.CalledProcessError, StopIteration):
            macros["NTests"] = "?"
    with open(os.path.join(out, "numbers2.tex"), "w") as f:
        f.write("% Generated by prepare_data2.py from the raw files. Do not edit.\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(f"wrote {len(macros)} macros to {out}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) not in (4, 5):
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    sys.exit(main(*sys.argv[1:]))
